/**
 * The icon to draw for a stored category or goal icon: a Lucide name as it is, an emoji as its
 * nearest icon (any other emoji as a plain tag), nothing for none.
 */
export function categoryIconName(stored: string | null | undefined): string | null {
  if (!stored) return null;
  const icon = stored.trim();
  if (!icon) return null;
  if (CATEGORY_ICONS[icon]) return icon;
  // Emoji are compared without variation selectors and skin tones
  const bare = icon.replace(/[︎️]|\u{1F3FB}|\u{1F3FC}|\u{1F3FD}|\u{1F3FE}|\u{1F3FF}/gu, '');
  return FROM_EMOJI[bare] ?? FROM_EMOJI[[...bare][0] ?? ''] ?? 'Tag';
}
